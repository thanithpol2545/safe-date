const Ctx = createContext({ lang: 'th', t: STR.th, toggle: () => {} });

export function LangProvider({ children }) {
  const [lang, setLang] = useState('th');
  const value = {
    lang,
    t: STR[lang],
    toggle: () => setLang((l) => (l === 'th' ? 'en' : 'th')),
  };
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);

// เลือกฟิลด์ตามภาษา: pick(obj, 'bio', lang) -> obj.bio หรือ obj.bioEn
export const pick = (obj, field, lang) =>
  lang === 'en' ? obj[field + 'En'] || obj[field] : obj[field];
